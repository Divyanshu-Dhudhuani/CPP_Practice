#include<bits/stdc++.h>
using namespace std;

int main(){
    //for loops
    //if we declare i inside for loop then it is only accessible in the for loop. If you want to access it outside then first declare it outside the loop
    for(int i = 1; i<=5; i=i+1){
        cout << "The value of i is: " << i << endl;
    }

    return 0;
}