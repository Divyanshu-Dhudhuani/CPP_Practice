#include<bits/stdc++.h>
using namespace std;

int main(){
    //int (stores the smallest set of integers) -10^9 to 10^9
    int x =10;

    //long (stores a bigger set of integers) -10^12 to 10^12
    long y =20;

    //long long (stores the largest set of integers) -10^18 to 10^18
    long long z=30;

    //float (less precise)
    float l =5.12;

    //double (more precise)
    double r =10.582;

    cout << "The value of x,y,z,l,r are: " << x <<" " <<y << " " <<z << " " <<l <<" " <<r;

    return 0;
}